"""Raccoon Dance art: the stage, the coach's head, FX and UI sprites.

Everything is generated by `tools/generate_dance_assets.py` into
`assets/dance/generated/`, with a `manifest.json` carrying the numbers that
belong to the art: outfit and rating colours, where the stage's lights hang,
where the coach stands. `load_art()` reads it once and caches it; a missing file
raises `AssetsMissingError` naming the generator to run. The renderer takes a
`DanceArt` in its constructor, so tests can pass `stub_art()` instead.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

import cv2
import numpy as np

ASSET_DIR = Path(__file__).resolve().parents[4] / "assets" / "dance" / "generated"
MANIFEST = ASSET_DIR / "manifest.json"
RATINGS = ("perfect", "super", "good", "ok", "x")
WORDS = ("get_ready", "count_3", "count_2", "count_1", "count_go", "superstar")


class AssetsMissingError(RuntimeError):
    pass


@dataclass
class DanceArt:
    stage: np.ndarray  # BGR, the full 1280x720 stage
    glow_trims: np.ndarray  # BGR, quarter resolution: the neon trims' glow, pulsed on the beat
    glow_floor: np.ndarray  # BGRA white, quarter resolution: the spotlight pool flaring
    glow_edge: np.ndarray  # BGRA white, quarter resolution: screen-edge glow (gold moves)
    beam: np.ndarray  # BGRA white: a light beam pointing down, apex at the top centre
    glow: np.ndarray  # BGRA white: soft dot
    sparkle: np.ndarray  # BGRA white: four-point twinkle
    burst: np.ndarray  # BGRA white: radial rays
    ring: np.ndarray  # BGRA white: the pictogram target ring
    star_full: np.ndarray  # BGRA
    star_empty: np.ndarray  # BGRA
    card: np.ndarray  # BGRA: pictogram card frame
    card_gold: np.ndarray  # BGRA: the gold move's card frame
    head: np.ndarray  # BGRA: the coach's raccoon head (with headphones)
    head_rim: np.ndarray  # BGRA white: a rim around the head's silhouette
    words: dict[str, np.ndarray]  # rating and banner words (RATINGS + WORDS), BGRA
    manifest: dict = field(default_factory=dict)

    def outfit(self, name: str | None) -> dict[str, tuple[int, int, int]]:
        outfits = self.manifest.get("outfits", {})
        spec = outfits.get(name or "neon") or outfits.get("neon") or next(iter(outfits.values()), {})
        return {k: tuple(int(c) for c in v) for k, v in spec.items()}

    def rating_colour(self, rating: str) -> tuple[int, int, int]:
        spec = self.manifest.get("ratings", {}).get(rating)
        return tuple(int(c) for c in spec["colour"]) if spec else (255, 255, 255)


_cache: DanceArt | None = None


def _read(name: str, flags: int = cv2.IMREAD_UNCHANGED) -> np.ndarray:
    path = ASSET_DIR / name
    if not path.exists():
        raise AssetsMissingError(f"missing dance asset {name}. Run:\n"
                                 f"  uv run python tools/generate_dance_assets.py")
    img = cv2.imread(str(path), flags)
    if img is None:
        raise AssetsMissingError(f"could not decode {path}")
    return img


def load_art(*, reload: bool = False) -> DanceArt:
    global _cache
    if _cache is not None and not reload:
        return _cache
    if not MANIFEST.exists():
        raise AssetsMissingError(f"missing {MANIFEST}. Run:\n"
                                 f"  uv run python tools/generate_dance_assets.py")
    spec = json.loads(MANIFEST.read_text())
    _cache = DanceArt(
        stage=_read("stage.png", cv2.IMREAD_COLOR),
        glow_trims=_read("glow_trims.png", cv2.IMREAD_COLOR),
        glow_floor=_read("glow_floor.png"),
        glow_edge=_read("glow_edge.png"),
        beam=_read("beam.png"),
        glow=_read("glow.png"),
        sparkle=_read("sparkle.png"),
        burst=_read("burst.png"),
        ring=_read("ring.png"),
        star_full=_read("star_full.png"),
        star_empty=_read("star_empty.png"),
        card=_read("card.png"),
        card_gold=_read("card_gold.png"),
        head=_read("coach_head.png"),
        head_rim=_read("coach_head_rim.png"),
        words={k: _read(f"word_{k}.png") for k in RATINGS + WORDS},
        manifest=spec,
    )
    return _cache


def stub_art() -> DanceArt:
    """Tiny flat placeholder art with the same shapes and manifest keys, for tests."""

    def sprite(w, h, colour=(255, 255, 255), a=200):
        img = np.zeros((h, w, 4), np.uint8)
        img[:, :, :3] = colour
        img[2:-2, 2:-2, 3] = a
        return img

    stage = np.full((720, 1280, 3), (40, 20, 30), np.uint8)
    q = (180, 320)
    outfit = {k: [200, 100, 200] for k in ("fur", "fur_dark", "top", "top_hi", "pants", "accent",
                                           "glove", "shoe", "rim", "glow")}
    outfit["ink"] = [30, 20, 25]
    return DanceArt(
        stage=stage, glow_trims=np.full((*q, 3), 20, np.uint8), glow_floor=sprite(320, 180),
        glow_edge=sprite(320, 180, a=40), beam=sprite(60, 200), glow=sprite(16, 16),
        sparkle=sprite(16, 16), burst=sprite(64, 64), ring=sprite(40, 40), star_full=sprite(32, 32),
        star_empty=sprite(32, 32, (80, 80, 80)), card=sprite(48, 52), card_gold=sprite(48, 52, (0, 200, 255)),
        head=sprite(64, 64, (200, 120, 160), 255), head_rim=sprite(64, 64),
        words={k: sprite(60 + 10 * len(k), 30) for k in RATINGS + WORDS},
        manifest={"outfits": {"neon": outfit},
                  "ratings": {k: {"colour": [255, 255, 255]} for k in RATINGS},
                  "head": {"centre": [0.5, 0.565], "chin": [0.5, 0.8], "face_width": 0.67},
                  "stage": {"lights": [[170, 94], [520, 94], [870, 94]], "horizon": 470,
                            "spot": [520, 652, 250, 56], "coach": [520, 660]},
                  "light_scale": 4},
    )
